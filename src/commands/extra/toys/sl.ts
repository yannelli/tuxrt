import type { CommandFn } from '../../types.ts';

const SMOKE = [
  '                      (@@) (  ) (@)  ( )  @@    ()    @     O     @',
  '                 (   )',
  '             (@@@@)',
  '          (    )',
  '',
];

const D51 = String.raw`      ====        ________                ___________
  _D _|  |_______/        \__I_I_____===__|_________|
   |(_)---  |   H\________/ |   |        =|___ ___|
   /     |  |   H  |  |     |   |         ||_| |_||
  |      |  |   H  |__--------------------| [___] |
  | ________|___H__/__|_____/[][]~\_______|       |
  |/ |   |-----------I_____I [][] []  D   |=======|__
__/ =| o |=-~~\  /~~\  /~~\  /~~\ ____Y___________|__
 |/-=|___|=    ||    ||    ||    |_____/~\___/
  \_/      \O=====O=====O=====O_/      \_/`.split('\n');

const COAL = String.raw`

    _________________
   _|                \_____A
 =|                        |
 -|                        |
__|________________________|_
|__________________________|_
   |_D__D__D_|  |_D__D__D_|
    \_/   \_/    \_/   \_/`.split('\n');

export const sl: CommandFn = (ctx) => {
  const width = Math.max(...D51.map((row) => row.length));
  const train = D51.map((row, i) => `${row.padEnd(width + 1)}${COAL[i]}`.trimEnd());
  ctx.stdout.write(`${[...SMOKE, ...train].join('\n')}\n`);
  return 0;
};
